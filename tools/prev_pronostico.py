# --- vista completa: 6 columnas de 21 px ---
COLS, ANCHO = 6, 21
horas = [15, 16, 17, 18, 19, 20]
temps = [26, 27, 25, 22, 19, 18]
tipos = ["sol", "sol", "parcial", "lluvia", "tormenta", "nube"]

g = blanco()
for i in range(COLS):
    x0 = i * ANCHO + (128 - COLS * ANCHO) // 2
    h = f"{horas[i]:02d}"
    mini(g, x0 + (ANCHO - (len(h) * 4 - 1)) // 2, 0, h)
    est(g, x0 + (ANCHO - 13) // 2, 6, ICONOS[tipos[i]])
    t = str(temps[i])
    texto5(g, x0 + (ANCHO - (len(t) * 6 - 1)) // 2, 21, t, 'o')

print("\n=== vista completa (o = caja del glifo 5x7 de la temperatura) ===")
