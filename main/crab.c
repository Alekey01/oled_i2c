void crab_draw(ssd1306_t *d, int x, int y, crab_frame_t frame)
{
    const char **rows = CRAB[frame % CRAB_FRAMES];
    for (int r = 0; r < CRAB_H; r++) {
        for (int c = 0; c < CRAB_W; c++) {
            if (rows[r][c] == '#') {
                ssd1306_pixel(d, x + c, y + r, true);
            }
        }
    }
}
